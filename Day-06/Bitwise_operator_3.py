a = 7               #0111
b = 3               #0011
bitAND = a & b
print(bitAND)       #result is 3 (0011)

bitOR = a | b
print(bitOR)        #result is 7 (0111)

bitXOR = a ^ b
print(bitXOR)       #result is 4 (0100) return1 when bits are different

bitNOT = ~a
print(bitNOT)       #result is -8 ...-(n+1).This is shorcut


